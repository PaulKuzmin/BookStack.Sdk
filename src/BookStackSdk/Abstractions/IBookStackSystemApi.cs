using BookStackSdk.Models;

namespace BookStackSdk.Abstractions;

/// <summary>
/// Сведения об установке (<c>GET /api/system</c>).
/// </summary>
/// <remarks>
/// Один маршрут, одно чтение. Прав администратора не требует, поэтому годится как самая дешёвая
/// проверка того, что адрес верен, установка жива и токен принят.
/// <para>
/// Главное применение: ЗАМОК ОТ ПРОГОНА ТЕСТОВ ПО ПРОДУ. Стендовый тест, который создаёт, правит
/// и удаляет содержимое, обязан сначала прочитать этот маршрут и сверить
/// <see cref="BookStackSystemInfo.InstanceId"/> с ожидаемым значением стенда, и упасть, если оно
/// не совпало. Идентификатор уникален на установку (замерено на стенде:
/// <c>261145ec-d28e-44fa-ad08-7cb29e279405</c>), тогда как адрес, имя и версия совпадают у прода
/// и у его копии. Сама проверка живёт в тестах, а не тут: SDK не решает за вызывающего, куда ему
/// можно ходить.
/// </para>
/// </remarks>
public interface IBookStackSystemApi
{
    /// <summary>Читает версию, адрес, имя, логотип и идентификатор установки.</summary>
    Task<BookStackSystemInfo?> GetAsync(CancellationToken ct = default);
}
