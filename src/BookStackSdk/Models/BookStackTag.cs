namespace BookStackSdk.Models;

/// <summary>
/// Тег сущности: пара имени и значения. Теги висят на страницах, книгах, главах и полках
/// одинаково, отдельного типа под каждую сущность у BookStack нет.
/// </summary>
/// <remarks>
/// ВАЖНО про запись: набор тегов заменяется ЦЕЛИКОМ, а не дополняется. В исходнике
/// <c>app/Activity/TagRepo.php</c>, метод <c>saveTagsToEntity()</c>, первой строкой стоит
/// <c>$entity-&gt;tags()-&gt;delete()</c>, и только потом сохраняются присланные. Замер на стенде
/// 17.08.2026 это подтверждает: страница с тегами <c>audience=client</c> и <c>lang=ru</c> после
/// <c>PUT</c> с единственным <c>lang=ru</c> осталась ровно с одним тегом.
/// <para>
/// Отсюда три разных смысла у поля <c>tags</c> в теле запроса, и путать их нельзя:
/// поля нет вовсе (в C# это <c>null</c>, которое не сериализуется) означает «теги не трогать»;
/// пустой список означает «снять все теги» (замерено: ответ вернул <c>[]</c>); непустой список
/// означает «пусть будут ровно эти». В исходнике за это отвечает <c>isset($input['tags'])</c>
/// в <c>app/Entities/Repos/BaseRepo.php</c>, а <c>isset</c> на <c>null</c> даёт ложь, то есть
/// явный <c>null</c> в JSON тоже НЕ снимет теги, он просто ничего не сделает.
/// </para>
/// </remarks>
public sealed class BookStackTag
{
    /// <summary>Пустой тег. Нужен сериализатору.</summary>
    public BookStackTag()
    {
    }

    /// <summary>Тег с именем и необязательным значением.</summary>
    public BookStackTag(string name, string? value = null)
    {
        Name = name;
        Value = value;
    }

    /// <summary>
    /// Имя тега.
    /// </summary>
    /// <remarks>
    /// Тег с пустым именем сервер молча выбрасывает, не отдавая ни ошибки, ни пометки:
    /// в <c>saveTagsToEntity()</c> стоит <c>filter(fn($tag) =&gt; boolval(trim($tag['name'])))</c>.
    /// То есть присланный список тегов и сохранённый список тегов могут разойтись при ответе 200.
    /// </remarks>
    public string? Name { get; set; }

    /// <summary>
    /// Значение тега.
    /// </summary>
    /// <remarks>
    /// При чтении значение никогда не приходит как <c>null</c>: тег, записанный без значения,
    /// возвращается с пустой строкой (замерено, в исходнике <c>trim($input['value'] ?? '')</c>).
    /// При записи <c>null</c> здесь означает «значения нет», и это законно.
    /// </remarks>
    public string? Value { get; set; }

    /// <summary>
    /// Порядковый номер тега.
    /// </summary>
    /// <remarks>
    /// ВАЖНО: полагаться на это число нельзя, оно всегда ноль. Замер на стенде: страница с тремя
    /// тегами вернула все три с <c>order: 0</c>. Причина в исходнике: <c>newInstanceFromInput()</c>
    /// заполняет только <c>name</c> и <c>value</c>, поле <c>order</c> остаётся значением по
    /// умолчанию из схемы. Поле оставлено в модели, потому что оно приходит в ответе, но сортировать
    /// по нему нечего. Порядок тегов задаётся порядком элементов списка при записи.
    /// </remarks>
    public int? Order { get; set; }

    /// <inheritdoc />
    public override string ToString()
        => string.IsNullOrEmpty(Value) ? Name ?? string.Empty : $"{Name}={Value}";
}
