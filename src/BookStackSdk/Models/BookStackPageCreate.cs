namespace BookStackSdk.Models;

/// <summary>
/// Тело создания страницы (<c>POST /api/pages</c>).
/// </summary>
/// <remarks>
/// Содержимое уходит markdown-ом. Поля <c>html</c>, которое API тоже принимает, здесь нет
/// НАМЕРЕННО, и вот чем это подтверждено. В исходнике
/// <c>app/Entities/Tools/PageContent.php</c>, метод <c>setNewHTML()</c>, последней строкой стоит
/// <c>$this-&gt;page-&gt;markdown = ''</c>: любая запись HTML-ом СТИРАЕТ исходный markdown страницы,
/// оставляя только готовую разметку. Замер на стенде 17.08.2026 это подтверждает: страница,
/// созданная с markdown, после <c>PUT</c> с одним лишь <c>html</c> вернулась с
/// <c>markdown: ""</c> и <c>editor: wysiwyg</c>.
/// <para>
/// Для документации, которая живёт в исходниках и раскатывается сюда, потеря источника это потеря
/// возможности сравнить и обновить. Поэтому единственный путь записи содержимого в этом SDK
/// markdown, а страницы, которые правят в HTML-редакторе BookStack, этим SDK и не создаются.
/// </para>
/// <para>
/// Второй замер того же места: если прислать И <c>markdown</c>, И <c>html</c>, применяется
/// markdown, а html молча игнорируется (в исходнике markdown проверяется раньше). То есть даже
/// будь поле <c>html</c> здесь, предсказуемого способа записать HTML рядом с markdown всё равно
/// нет.
/// </para>
/// </remarks>
public sealed class BookStackPageCreate
{
    /// <summary>
    /// Книга, в которую кладётся страница.
    /// </summary>
    /// <remarks>
    /// Обязательно ровно одно из двух: <see cref="BookId"/> или <see cref="ChapterId"/>
    /// (в правилах маршрута это <c>required_without</c> в обе стороны). Если задана глава, книга не
    /// нужна: сервер возьмёт книгу главы сам, и в ответе <c>book_id</c> придёт заполненным
    /// (замерено).
    /// </remarks>
    public int? BookId { get; set; }

    /// <summary>Глава, в которую кладётся страница. Альтернатива <see cref="BookId"/>.</summary>
    public int? ChapterId { get; set; }

    /// <summary>
    /// Заголовок страницы. Сервер требует его непустым, ограничение длины 255 символов.
    /// </summary>
    /// <remarks>
    /// Отказ «The name field is required» имеет ВТОРОЙ смысл: тем же текстом сервер отвечает, когда
    /// тело не разобралось целиком (испорченная кодировка, BOM, потерянный <c>Content-Type</c>).
    /// Со стороны SDK эта дорога перекрыта в <see cref="Internal.BookStackJson"/>, но если такой
    /// отказ всё же придёт, читать его как «имя не задано» можно только убедившись, что имя
    /// действительно не задавали.
    /// </remarks>
    public string? Name { get; set; }

    /// <summary>
    /// Содержимое страницы в markdown.
    /// </summary>
    /// <remarks>
    /// Пустая строка не годится: правило маршрута это <c>required_without:html</c>, а пустое
    /// значение Laravel считает отсутствующим, и создание отвалится с 422.
    /// <para>
    /// Картинки, вставленные как <c>data:</c>-URI прямо в markdown, сервер вынимает и сохраняет в
    /// галерею сам, подменяя ссылки (так написано в живой доке маршрута и в исходнике
    /// <c>extractBase64ImagesFromMarkdown()</c>). Это не отменяет отдельной загрузки картинок, но
    /// объясняет, почему присланный markdown может вернуться изменённым.
    /// </para>
    /// </remarks>
    public string? Markdown { get; set; }

    /// <summary>
    /// Позиция среди соседей.
    /// </summary>
    /// <remarks>
    /// Если не задать, сервер назначит номер сам, продолжив нумерацию соседей (замерено).
    /// </remarks>
    public int? Priority { get; set; }

    /// <summary>
    /// Теги страницы. <c>null</c> означает «тегов не ставить».
    /// </summary>
    /// <remarks>
    /// При создании разницы между <c>null</c> и пустым списком нет: тегов не будет ни там, ни там.
    /// Разница появляется при обновлении, см. <see cref="BookStackPageUpdate.Tags"/>.
    /// </remarks>
    public List<BookStackTag>? Tags { get; set; }
}
