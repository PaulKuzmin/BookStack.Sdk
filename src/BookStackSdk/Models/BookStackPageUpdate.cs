namespace BookStackSdk.Models;

/// <summary>
/// Тело обновления страницы (<c>PUT /api/pages/{id}</c>).
/// </summary>
/// <remarks>
/// Обновление ЧАСТИЧНОЕ, несмотря на метод <c>PUT</c>: неупомянутые поля остаются как были.
/// Замер на стенде 17.08.2026: <c>PUT</c> с одним лишь <c>name</c> сохранил и содержимое, и оба
/// тега страницы. Именно поэтому здесь все поля nullable, а сериализация не отправляет <c>null</c>:
/// «не трогать» и «очистить» разводятся отсутствием и присутствием поля в теле.
/// <para>
/// Отдельного метода <c>PATCH</c> у BookStack нет вовсе, в живой доке <c>/api/docs.json</c> все
/// изменяющие маршруты объявлены как <c>PUT</c>.
/// </para>
/// </remarks>
public sealed class BookStackPageUpdate
{
    /// <summary>
    /// Перенести страницу в другую книгу.
    /// </summary>
    /// <remarks>
    /// Это не просто смена поля, а перенос: в исходнике
    /// <c>PageApiController::update()</c> при заданном родителе вызывается
    /// <c>PageRepo::move()</c>, и он дополнительно требует права на УДАЛЕНИЕ страницы из старого
    /// места. То есть токен, которому хватает прав на правку, может не суметь перенести.
    /// </remarks>
    public int? BookId { get; set; }

    /// <summary>Перенести страницу в другую главу. Те же оговорки, что и у <see cref="BookId"/>.</summary>
    public int? ChapterId { get; set; }

    /// <summary>
    /// Новый заголовок.
    /// </summary>
    /// <remarks>
    /// Смена имени ПЕРЕСЧИТЫВАЕТ слаг, то есть меняет адрес страницы, см.
    /// <see cref="BookStackPage.Slug"/>.
    /// </remarks>
    public string? Name { get; set; }

    /// <summary>
    /// Новое содержимое в markdown.
    /// </summary>
    /// <remarks>
    /// <c>null</c> оставляет содержимое нетронутым. Пустая строка ОЧИЩАЕТ страницу: замер показал,
    /// что после <c>PUT</c> с <c>markdown: ""</c> и <c>markdown</c>, и <c>html</c> вернулись
    /// пустыми. В исходнике за это отвечает ветка <c>if ($haveInput &amp;&amp; $inputEmpty)</c>,
    /// которая ставит пустой HTML. Различить «поле не слали» и «слали пустым» может только тот, кто
    /// собирает тело, поэтому очистка здесь именно явная.
    /// <para>
    /// Про то, почему поля <c>html</c> в этом SDK нет, и что происходит при записи HTML, см.
    /// <see cref="BookStackPageCreate"/>.
    /// </para>
    /// </remarks>
    public string? Markdown { get; set; }

    /// <summary>Новая позиция среди соседей.</summary>
    public int? Priority { get; set; }

    /// <summary>
    /// Новый набор тегов.
    /// </summary>
    /// <remarks>
    /// Три состояния, и путать их дорого: <c>null</c> означает «теги не трогать», пустой список
    /// означает «снять все теги», непустой означает «пусть будут ровно эти, прежние удалить».
    /// Подробности и подтверждение из исходников в описании <see cref="BookStackTag"/>.
    /// <para>
    /// Побочное следствие: запись тегов двигает <c>updated_at</c> страницы, потому что после
    /// сохранения тегов в исходнике стоит явный <c>touch()</c>. То есть обход «что изменилось с
    /// прошлого раза» увидит страницу, у которой поменялась только разметка тегов.
    /// </para>
    /// </remarks>
    public List<BookStackTag>? Tags { get; set; }
}
