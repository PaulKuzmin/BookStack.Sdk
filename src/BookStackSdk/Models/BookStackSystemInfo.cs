namespace BookStackSdk.Models;

/// <summary>
/// Сведения об установке (<c>GET /api/system</c>).
/// </summary>
/// <remarks>
/// Маршрут дешёвый и не требует прав администратора, поэтому годится и как проверка живости,
/// и как проверка того, что токен вообще принят.
/// </remarks>
public sealed class BookStackSystemInfo
{
    /// <summary>Версия, например <c>v26.05.3</c> (замерено на стенде).</summary>
    /// <remarks>
    /// Приходит с буквой <c>v</c> впереди, то есть это НЕ то, что разберёт <c>Version.Parse</c>.
    /// Оставлено строкой как есть: чистить строку значило бы решать за вызывающего, а сравнивать
    /// версии по этому полю всё равно ненадёжно (нумерация календарная).
    /// </remarks>
    public string? Version { get; set; }

    /// <summary>
    /// Идентификатор установки, уникальный на установку.
    /// </summary>
    /// <remarks>
    /// ВАЖНО: это и есть замок от прогона тестов по проду. Замерено 17.08.2026, стенд отдаёт
    /// <c>261145ec-d28e-44fa-ad08-7cb29e279405</c>, и у любой другой установки значение будет иным.
    /// Ни адрес, ни имя, ни версия таким замком быть не могут: адрес переезжает за прокси, имя
    /// у копии прода совпадает с продом, а версия совпадает у всех установок одного выпуска.
    /// <para>
    /// Способ применения: стендовый тест перед тем, как что-то создавать или удалять, читает
    /// <c>GET /api/system</c> и сверяет это поле с ожидаемым; не совпало, значит указали не тот
    /// адрес или не тот токен, и тест обязан упасть ДО первой правки, а не после. Проверка живёт
    /// в тестах, а не здесь: SDK не решает, куда вызывающему можно ходить.
    /// </para>
    /// </remarks>
    public string? InstanceId { get; set; }

    /// <summary>Имя установки, как оно показано в интерфейсе.</summary>
    public string? AppName { get; set; }

    /// <summary>Адрес логотипа. <c>null</c>, если логотип не задан (так написано в живой доке).</summary>
    public string? AppLogo { get; set; }

    /// <summary>
    /// Базовый адрес установки, как её знает сама установка (настройка <c>APP_URL</c>).
    /// </summary>
    /// <remarks>
    /// Может отличаться от адреса, по которому мы сюда пришли: BookStack собирает по нему все
    /// абсолютные ссылки в ответах (адреса картинок, <c>url</c> в выдаче поиска, ссылки вложений).
    /// Расхождение этого поля с адресом клиента объясняет ссылки, которые «ведут не туда»,
    /// притом что сам ответ верен.
    /// </remarks>
    public string? BaseUrl { get; set; }
}
