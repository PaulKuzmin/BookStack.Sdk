using System.Text.RegularExpressions;

namespace BookStackTools;

/// <summary>
/// Мелочи разбора markdown, общие для инструментов.
/// </summary>
/// <remarks>
/// Здесь ровно одно правило и ровно одна причина его завести: правка текста НЕ ДОЛЖНА заходить в
/// огороженные блоки кода. Внутри них лежат команды, конфиги и примеры разметки, то есть ровно те
/// места, где путь или адрес это данные, а не переход. Замена, вошедшая туда, портит документ молча:
/// команда в инструкции остаётся выполнимой на вид и неверной по сути.
/// </remarks>
internal static class Markdown
{
    /// <summary>Граница огороженного блока: три обратных апострофа или три тильды.</summary>
    private static readonly Regex Fence = new(@"^\s{0,3}(```|~~~)");

    /// <summary>
    /// Знаки нулевой ширины, которые приложение на той стороне срезает по краям вместе с пробелами.
    /// </summary>
    /// <remarks>
    /// Метка порядка байтов, пробел нулевой ширины и метка направления письма. Для .NET это НЕ
    /// пробельные знаки (<see cref="char.IsWhiteSpace(char)"/> для них ложь), поэтому обычный
    /// <see cref="string.Trim()"/> их не тронет, а сервер тронет. Текст, начинающийся с такого
    /// знака, иначе никогда не совпал бы сам с собой, и страница переписывалась бы каждый прогон.
    /// </remarks>
    private static readonly char[] Invisible = ['﻿', '​', '‎'];

    /// <summary>
    /// Приводит текст к виду, в котором его можно сравнивать с тем, что вернул портал.
    /// </summary>
    /// <remarks>
    /// Сравнивать «в лоб» нельзя по двум причинам сразу. Файл на диске хранится с <c>CRLF</c>, а
    /// портал отдаёт что у него лежит; и приложение на той стороне подрезает присланный текст с
    /// обоих концов, включая знаки нулевой ширины. Без приведения повторный прогон переписывал бы
    /// портал целиком и каждый раз.
    /// <para>
    /// Приведение живёт ТОЛЬКО в сравнении: на портал уходит текст как есть.
    /// </para>
    /// </remarks>
    public static string NormalizeForCompare(string text)
        => text.Replace("\r\n", "\n").Replace('\r', '\n').Trim().Trim(Invisible).Trim();

    /// <summary>
    /// Применяет преобразование к каждой строке, кроме тех, что внутри огороженных блоков.
    /// </summary>
    /// <param name="text">Исходный текст.</param>
    /// <param name="transform">Что делать со строкой вне блоков.</param>
    /// <remarks>
    /// Перевод строки сохраняется тот же, что был: текст разбирается по <c>\n</c>, а <c>\r</c>
    /// остаётся в конце строки и уезжает обратно нетронутым. Иначе инструмент, правящий одну ссылку,
    /// переписывал бы заодно все переводы строк документа.
    /// </remarks>
    public static string MapLinesOutsideFences(string text, Func<string, string> transform)
    {
        var lines = text.Split('\n');
        var insideFence = false;

        for (var i = 0; i < lines.Length; i++)
        {
            if (Fence.IsMatch(lines[i]))
            {
                insideFence = !insideFence;
                continue;
            }

            if (!insideFence)
                lines[i] = transform(lines[i]);
        }

        return string.Join('\n', lines);
    }
}
