using System;

namespace BookStackSdk.Tests.Stand;

/// <summary>
/// Строгий режим стендовых проверок: пропуск запрещён, ненастроенный или неотвечающий стенд
/// обязан краснеть.
/// </summary>
/// <remarks>
/// Зачем он нужен. Пропуск с причиной хорош ровно до того момента, пока кто-то не начинает читать
/// зелёный прогон как доказательство. В этом проекте уже дважды случалось, что стендовые проверки
/// были зелёными ВПУСТУЮ: тест не выполнялся вовсе, а отчёт выглядел успешным. Поэтому есть
/// второй режим, который включается на сборочном агенте и при приёмке: в нём тот же самый тест не
/// пропускается, а идёт в прогон и падает с названной причиной.
/// <para>
/// ⚠️ ФЛАГ ЧИТАЕТСЯ ПРЯМО ИЗ ОКРУЖЕНИЯ ПРОЦЕССА, и никакой конфигурации приложения тут нет
/// намеренно. Ровно на подмешивании конфигурации сломался <c>DapperPlusLicenseBootTests</c> в
/// AltWayService: тест опирался на значение из <c>appsettings.json</c>, а конфигурация ASP.NET
/// читает ещё и переменные окружения, и in-memory источник, и пользовательские секреты. Когда на
/// машине разработки завели переменные лицензии, исход теста поменялся на противоположный, притом
/// что код не менялся ни на строку (замер 15.08.2026). Исход проверки обязан зависеть от кода, а
/// не от того, какие источники настроек сегодня подцепились. Один источник, названный явно, это и
/// есть лекарство.
/// </para>
/// <para>
/// Значение читается один раз, по той же причине, что и в <see cref="StandGate"/>: атрибут
/// смотрит на него при обнаружении тестов, фикстура при прогоне, и эти два взгляда обязаны
/// совпадать.
/// </para>
/// </remarks>
public static class StrictStand
{
    /// <summary>Переменная окружения, включающая строгий режим.</summary>
    public const string Variable = "ALTWAY_TESTS_REQUIRE_STAND";

    static StrictStand() => IsEnabled = IsTruthy(Environment.GetEnvironmentVariable(Variable));

    /// <summary>Строгий режим включён: пропускать стендовые проверки нельзя.</summary>
    public static bool IsEnabled { get; }

    /// <summary>
    /// Разбор значения переменной.
    /// </summary>
    /// <remarks>
    /// ⚠️ Правило намеренно несимметрично: выключением считаются только ПЕРЕЧИСЛЕННЫЕ значения,
    /// а любое другое непустое значение включает строгий режим. Причина в цене ошибки. Опечатка
    /// вида <c>ALTWAY_TESTS_REQUIRE_STAND=да</c> при симметричном разборе тихо оставила бы прогон
    /// нестрогим, то есть человек думал бы, что стенд проверен, а прогон бы всё пропустил. Это
    /// ровно тот исход, ради предотвращения которого режим и заведён. Обратная ошибка (лишняя
    /// строгость) видна сразу и чинится одной переменной.
    /// </remarks>
    public static bool IsTruthy(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return false;

        return value.Trim().ToLowerInvariant() switch
        {
            "0" or "false" or "no" or "off" or "нет" => false,
            _ => true,
        };
    }

    /// <summary>Чего требует строгий режим. Для сообщений об отказе.</summary>
    public static string Demand =>
        $"{Variable} включён, значит стенд обещан и обязан быть настроен и жив. " +
        "Либо поднимите стенд и задайте переменные, либо снимите строгий режим " +
        $"({Variable}=0), и тогда стендовые проверки будут пропускаться с причиной.";
}
